class SequenceDataset(Dataset):
    """
    Dataset for sequential recommendation.
    Each sample is a user's interaction sequence.
    """
    def __init__(self, user_seq, item_num, max_len=50):
        """
        Parameters
        ----------
        user_seq : dict
            {user_id: [item1, item2, ...]} ordered by time
        item_num : int
            total number of items
        max_len : int
            maximum sequence length
        """
        self.user_seq = user_seq
        self.item_num = item_num
        self.max_len = max_len
        self.users = list(user_seq.keys())

    def __len__(self):
        return len(self.users)

    def __getitem__(self, idx):
        user = self.users[idx]
        seq = self.user_seq[user]

        if len(seq) < 2:
            seq = seq + [0]

        seq_items = seq[:-1][-self.max_len:]
        target = seq[-1]


        pad_len = self.max_len - len(seq_items)
        seq_items = [0] * pad_len + seq_items

        return (
            torch.LongTensor(seq_items),
            torch.LongTensor([target]),
            torch.LongTensor([user])
        )
