import torch
from torch.utils.data import Dataset, DataLoader
from torch.utils.data import BatchSampler, RandomSampler, SequentialSampler


def get_dataloader(ds, batch_size, shuffle, num_workers=4):  
    if isinstance(ds, BasicDataset):
        sampler = RandomSampler(ds) if shuffle else SequentialSampler(ds)
        batches = BatchSampler(sampler, batch_size, drop_last=False)
        # Index an entire batch at once, preserving PyTorch's sampler order.
        return DataLoader(ds, batch_size=None, sampler=batches, num_workers=num_workers)
    return DataLoader(
        ds, batch_size=batch_size, shuffle=shuffle, num_workers=num_workers)


